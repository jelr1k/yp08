CREATE TABLE users (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 username VARCHAR(50) NOT NULL UNIQUE,
 email VARCHAR(255) NOT NULL UNIQUE,
 password_hash VARCHAR(255) NOT NULL,
 role VARCHAR(20) NOT NULL DEFAULT 'viewer' CHECK (role IN ('viewer','designer','admin')),
 avatar_url VARCHAR(500),
 bio TEXT,
 contact_url VARCHAR(500),
 is_blocked BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE TABLE categories (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(100) NOT NULL UNIQUE,
 slug VARCHAR(120) NOT NULL UNIQUE,
 description TEXT
);
CREATE TABLE works (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 category_id INTEGER NOT NULL REFERENCES categories(id) ON DELETE RESTRICT,
 title VARCHAR(200) NOT NULL,
 description TEXT,
 is_hidden BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_works_user_id ON works(user_id);
CREATE INDEX ix_works_category_id ON works(category_id);
CREATE TABLE work_images (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 work_id INTEGER NOT NULL REFERENCES works(id) ON DELETE CASCADE,
 file_url VARCHAR(500) NOT NULL,
 alt_text VARCHAR(255),
 sort_order INTEGER NOT NULL DEFAULT 0,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_work_images_work_id ON work_images(work_id);
CREATE TABLE tags (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 name VARCHAR(50) NOT NULL UNIQUE,
 slug VARCHAR(70) NOT NULL UNIQUE
);
CREATE TABLE work_tags (
 work_id INTEGER NOT NULL REFERENCES works(id) ON DELETE CASCADE,
 tag_id INTEGER NOT NULL REFERENCES tags(id) ON DELETE CASCADE,
 PRIMARY KEY (work_id, tag_id)
);
CREATE TABLE comments (
 id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
 work_id INTEGER NOT NULL REFERENCES works(id) ON DELETE CASCADE,
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 text TEXT NOT NULL,
 is_hidden BOOLEAN NOT NULL DEFAULT FALSE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);
CREATE INDEX ix_comments_work_id ON comments(work_id);
CREATE INDEX ix_comments_user_id ON comments(user_id);
CREATE TABLE likes (
 user_id INTEGER NOT NULL REFERENCES users(id) ON DELETE CASCADE,
 work_id INTEGER NOT NULL REFERENCES works(id) ON DELETE CASCADE,
 created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
 PRIMARY KEY (user_id, work_id)
);